// 0, empty and NaN retain the previous configured price, including on repeated reads.
export function buildEstimateRateUpdates(rawValues, context) {
  return ESTIMATE_RATE_BINDINGS.map(({ target, path }, index) => {
    const previous = path.reduce((value, key) => value[key], context[target]);
    return { target, path, value: Number(rawValues[index]) || previous };
  });
}

